// Regenerates docs/inventory.md: routes, tools, blog posts, framer-motion users, fonts and images.
// Run with `node scripts/inventory.mjs`. Reads the same modules the sitemap generator uses.
import { createServer } from 'vite';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import path from 'node:path';
import fs from 'node:fs/promises';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');

async function loadData() {
  const vite = await createServer({
    root,
    configFile: path.join(root, 'vite.config.ts'),
    server: { middlewareMode: true },
    appType: 'custom',
  });
  const { TOOLS, STATIC_ROUTES } = await vite.ssrLoadModule('/src/content/routes.ts');
  const { BLOG_POSTS } = await vite.ssrLoadModule('/src/data/blog/index.ts');
  const { BLOG_CATEGORIES } = await vite.ssrLoadModule('/src/data/blogCategories.ts');
  await vite.close();
  return { TOOLS, STATIC_ROUTES, BLOG_POSTS, BLOG_CATEGORIES };
}

function git(args) {
  return execFileSync('git', args, { cwd: root, encoding: 'utf8' }).trim();
}

/** Date of the commit that first added a file (its real first publication, since main auto-deploys). */
function firstCommitDate(file) {
  const out = git(['log', '--diff-filter=A', '--follow', '--format=%ad', '--date=short', '--', file]);
  return out.split('\n').filter(Boolean).pop() ?? '';
}

function blockText(b) {
  switch (b.type) {
    case 'heading': case 'paragraph': case 'quote': return b.text;
    case 'callout': return `${b.title ?? ''} ${b.text}`;
    case 'list': return b.items.join(' ');
    default: return '';
  }
}

function wordCount(post) {
  const text = [
    ...post.content.map(blockText),
    ...(post.keyTakeaways ?? []),
    ...(post.faqs ?? []).flatMap((f) => [f.question, f.answer]),
  ].join(' ').replace(/<[^>]+>/g, ' ');
  return text.split(/\s+/).filter(Boolean).length;
}

function imageSource(src) {
  if (!src) return 'none (falls back to emblem / default OG image)';
  if (src.includes('images.pexels.com')) return 'Pexels hotlink — Pexels License; photographer not credited';
  if (src.startsWith('/og/blog/')) return 'Generated OG card (build-time screenshot; missing in production)';
  return src;
}

async function listFiles(dir) {
  const entries = await fs.readdir(path.join(root, dir), { withFileTypes: true });
  return entries.filter((e) => e.isFile()).map((e) => `${dir}/${e.name}`);
}

async function main() {
  const { TOOLS, STATIC_ROUTES, BLOG_POSTS, BLOG_CATEGORIES } = await loadData();
  const categories = BLOG_CATEGORIES.filter((c) => c.id !== 'all');
  const routeCount = STATIC_ROUTES.length + TOOLS.length + BLOG_POSTS.length + categories.length;
  const live = TOOLS.filter((t) => t.status === 'live');

  const motionFiles = git(['grep', '-l', "from 'framer-motion'", '--', 'src']).split('\n').filter(Boolean);
  const indexHtml = await fs.readFile(path.join(root, 'index.html'), 'utf8');
  const fontFamilies = [...new Set([...indexHtml.matchAll(/family=([A-Za-z+]+)/g)].map((m) => m[1].replace(/\+/g, ' ')))];
  const publicImages = (await listFiles('public')).filter((f) => /\.(png|svg|jpe?g|webp|ico)$/i.test(f));
  const assetImages = (await listFiles('src/assets')).filter((f) => /\.(png|svg|jpe?g|webp)$/i.test(f));
  const contentImages = BLOG_POSTS.flatMap((p) => p.content.filter((b) => b.type === 'image').map((b) => ({ post: p.slug, src: b.src })));

  const lines = [];
  lines.push('# VediCosmic inventory', '');
  lines.push(`Generated by \`node scripts/inventory.mjs\` on ${new Date().toISOString().slice(0, 10)} from commit \`${git(['rev-parse', '--short', 'HEAD'])}\`.`, '');
  lines.push('## Routes', '');
  lines.push(`${routeCount} public URLs: ${STATIC_ROUTES.length} static pages, ${TOOLS.length} tools, ${BLOG_POSTS.length} blog posts, ${categories.length} blog categories. Database-authored posts are added at build time (0 at the time of writing). Admin route \`/vc-portal-x7\` and the hidden OG-card route \`/og/blog/:slug\` are not public pages.`, '');
  lines.push('| Path | Label | Indexable |', '|---|---|---|');
  for (const r of STATIC_ROUTES) lines.push(`| \`${r.path}\` | ${r.seoLabel} | ${r.indexable ? 'yes' : 'no'} |`);
  for (const c of categories) lines.push(`| \`/blog/category/${c.id}\` | Blog category: ${c.label} | yes |`);
  lines.push('');

  lines.push('## Tools', '');
  lines.push(`${TOOLS.length} tools in \`src/content/routes.ts\`: ${live.length} live, ${TOOLS.length - live.length} coming soon. Any text that states a tool count must use \`liveTools().length\`.`, '');
  lines.push('| Slug | Name | Category | Status | Indexable |', '|---|---|---|---|---|');
  for (const t of TOOLS) lines.push(`| \`/tools/${t.slug}\` | ${t.name} | ${t.category} | ${t.status} | ${t.indexable ? 'yes' : 'no'} |`);
  lines.push('');

  lines.push('## Blog posts', '');
  lines.push('"Dated" is the `publishedAt` value shown to readers; "First committed" is when the post file entered the repo (main auto-deploys, so this is the earliest it could have been public).', '');
  lines.push('| Slug | Category | Dated | First committed | Author | Words | Hero image |', '|---|---|---|---|---|---|---|');
  for (const p of BLOG_POSTS) {
    const file = `src/data/blog/posts/${p.slug}.ts`;
    lines.push(`| \`${p.slug}\` | ${p.category} | ${p.publishedAt} | ${firstCommitDate(file)} | ${p.authorId ?? '—'} | ${wordCount(p)} | ${imageSource(p.heroImage)} |`);
  }
  lines.push('');

  lines.push('## Components importing framer-motion', '');
  lines.push(`${motionFiles.length} files:`, '');
  for (const f of motionFiles) lines.push(`- \`${f}\``);
  lines.push('');

  lines.push('## Fonts', '');
  lines.push('Loaded from Google Fonts (`index.html`), not self-hosted. Licence: SIL Open Font License for all families listed.', '');
  for (const f of fontFamilies) lines.push(`- ${f}`);
  lines.push('');

  lines.push('## Images', '');
  lines.push('| File | Source / licence |', '|---|---|');
  for (const f of [...publicImages, ...assetImages]) lines.push(`| \`${f}\` | Site logo/icon — source and licence not recorded in the repo; owner to confirm |`);
  for (const i of contentImages) lines.push(`| in \`${i.post}\` | ${imageSource(i.src)} |`);
  lines.push('');

  await fs.mkdir(path.join(root, 'docs'), { recursive: true });
  await fs.writeFile(path.join(root, 'docs', 'inventory.md'), lines.join('\n'));
  console.log(`[inventory] wrote docs/inventory.md (${routeCount} routes, ${TOOLS.length} tools, ${BLOG_POSTS.length} posts)`);
}

main().catch((err) => { console.error(err); process.exitCode = 1; });
