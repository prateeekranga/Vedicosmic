// Writes dist/.htaccess (Apache/LiteSpeed on Hostinger) for the pre-rendered site, and for a staging
// build (DEPLOY_TARGET=staging) also a robots.txt and header that keep staging out of search.
// Redirects come from src/content/redirects.ts. Run after scripts/ssg.mjs.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIST = path.join(root, 'dist');
const staging = process.env.DEPLOY_TARGET === 'staging';
const { REDIRECTS, GONE_PREFIXES } = await import(pathToFileURL(path.join(root, 'dist-ssr', 'entry-server.js')).href);

const regex = (p) => p.replace(/^\//, '').replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

const lines = [
  '# Generated by scripts/generate-htaccess.mjs (redirects: src/content/redirects.ts). Do not edit by hand.',
  'Options -MultiViews -Indexes',
  '# Pre-rendered pages live in folders (about/index.html) but their URLs have no trailing slash.',
  'DirectorySlash Off',
  'ErrorDocument 404 /404.html',
  'RewriteEngine On',
  '',
  "# One host. Hostinger's edge already sends http:// to https://.",
  'RewriteCond %{HTTP_HOST} ^www\\.vedicosmic\\.com$ [NC]',
  'RewriteRule ^(.*)$ https://vedicosmic.com/$1 [R=301,L]',
  '',
  '# Changed URLs: a single 301 each. (REDIRECT_STATUS is empty only for the visitor\'s own request,',
  '# so these never fire on the internal rewrites below.)',
  ...REDIRECTS.flatMap(({ from, to }) => ['RewriteCond %{ENV:REDIRECT_STATUS} ^$', `RewriteRule ^${regex(from)}/?$ ${to} [R=301,L]`]),
  '',
  '# Gone for good.',
  ...GONE_PREFIXES.map((prefix) => `RewriteRule ^${regex(prefix)}.+ - [G,L]`),
  '',
  '# One URL per page: no trailing slash, no /index.html.',
  'RewriteCond %{ENV:REDIRECT_STATUS} ^$',
  'RewriteRule ^(.+)/$ /$1 [R=301,L]',
  'RewriteCond %{ENV:REDIRECT_STATUS} ^$',
  'RewriteRule ^(.*?)/?index\\.html$ /$1 [R=301,L]',
  '',
  '# /about is served from about/index.html without a redirect. Anything else missing gets /404.html.',
  'RewriteCond %{REQUEST_FILENAME} -d',
  'RewriteCond %{REQUEST_FILENAME}/index.html -f',
  'RewriteRule ^(.+)$ $1/index.html [L]',
  '',
  '<IfModule mod_setenvif.c>',
  '  SetEnvIf Request_URI "^/assets/" VC_HASHED',
  '  SetEnvIf Request_URI "^/(images|og|places)/" VC_MEDIA',
  '  SetEnvIf Request_URI "^/vc-portal-x7" VC_ADMIN',
  '</IfModule>',
  '<IfModule mod_headers.c>',
  '  Header always set X-Content-Type-Options "nosniff"',
  '  Header always set Referrer-Policy "strict-origin-when-cross-origin"',
  '  Header always set Permissions-Policy "camera=(), microphone=(), payment=(), usb=(), geolocation=(self)"',
  '  # Pages for a few minutes; images, share cards and place files for a day; files in /assets/,',
  '  # whose names change with their content, for a year. Later lines override earlier ones.',
  '  Header set Cache-Control "public, max-age=300"',
  '  Header set Cache-Control "public, max-age=86400" env=VC_MEDIA',
  '  Header set Cache-Control "public, max-age=31536000, immutable" env=VC_HASHED',
  '  Header always set X-Robots-Tag "noindex, nofollow" env=VC_ADMIN',
  '  Header always set X-Robots-Tag "noindex, nofollow" env=REDIRECT_VC_ADMIN',
  ...(staging ? ['  # Staging: never indexed.', '  Header always set X-Robots-Tag "noindex, nofollow"'] : []),
  '</IfModule>',
  '',
];

fs.writeFileSync(path.join(DIST, '.htaccess'), lines.join('\n'));
if (staging) fs.writeFileSync(path.join(DIST, 'robots.txt'), 'User-agent: *\nDisallow: /\n');
console.log(`[htaccess] wrote dist/.htaccess (${REDIRECTS.length} redirects${staging ? ', staging: noindex' : ''})`);
