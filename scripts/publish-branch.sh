#!/usr/bin/env bash
# Publishes the built site in ./dist to a branch that Hostinger's Git deployment watches:
#   scripts/publish-branch.sh deploy     (production)
#   scripts/publish-branch.sh staging    (staging.vedicosmic.com)
# The branch holds dist/ plus a package.json whose build step does nothing, because Hostinger
# runs `npm install && npm run build` and serves dist/. Runs in GitHub Actions (CI workflow).
set -euo pipefail

BRANCH="$1"
SOURCE="${GITHUB_SHA:-$(git rev-parse HEAD)}"
SITE_DIR="$PWD/dist"
WORK="$(mktemp -d)"

git config user.name "github-actions[bot]"
git config user.email "41898282+github-actions[bot]@users.noreply.github.com"

if git ls-remote --exit-code --heads origin "$BRANCH" > /dev/null; then
  git fetch --depth 1 origin "$BRANCH"
  git worktree add --detach "$WORK" FETCH_HEAD
else
  git worktree add --detach "$WORK"
  git -C "$WORK" checkout --orphan "$BRANCH"
  git -C "$WORK" rm -rfq .
fi

find "$WORK" -mindepth 1 -maxdepth 1 ! -name .git -exec rm -rf {} +
cp -R "$SITE_DIR" "$WORK/dist"
cat > "$WORK/package.json" <<'JSON'
{
  "name": "vedicosmic-site",
  "private": true,
  "description": "Pre-built site published by the CI workflow. Do not edit; change the main branch instead.",
  "scripts": {
    "build": "node -e \"console.log('Site is pre-built in dist/')\""
  }
}
JSON
cat > "$WORK/README.md" <<EOF
# VediCosmic: built site

Generated by the CI workflow from commit ${SOURCE}. Do not edit this branch: change \`main\` instead.
EOF

git -C "$WORK" add -A
if git -C "$WORK" diff --cached --quiet; then
  echo "[publish] $BRANCH is already up to date."
else
  git -C "$WORK" commit -q -m "Site build from ${SOURCE:0:7}"
  git -C "$WORK" push -q origin "HEAD:refs/heads/$BRANCH"
  echo "[publish] pushed ${SOURCE:0:7} to $BRANCH."
fi
git worktree remove --force "$WORK"
